// Builds seed SQL for the database from the demo catalog (admin-v2/assets/data.js).
//   node backend/seed/build-seed.js
// Writes backend/supabase/seed/01-catalog.sql (reference data, stores, products, offers, coupons)
// and backend/supabase/seed/02-history.sql (90 days of lowest-price history per product and market).
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.join(__dirname, '..', '..');
const OUT = path.join(ROOT, 'backend', 'supabase', 'seed');
const HISTORY_DAYS = 90;

// Run data.js in a sandbox that looks like a browser with empty storage.
const sandbox = { window: {}, localStorage: { getItem: () => null, setItem() {} }, console, Math, JSON, Date };
sandbox.window = sandbox;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT, 'admin-v2', 'assets', 'data.js'), 'utf8'), sandbox);
const D = sandbox.DOABNO_DATA;
const FULL = D.admin;

const q = v => (v === null || v === undefined ? 'null' : "'" + String(v).replace(/'/g, "''") + "'");
const n = v => (v === null || v === undefined ? 'null' : String(v));
const arr = a => "array[" + a.map(q).join(', ') + "]::text[]";
const insert = (table, cols, rows, tail) => rows.length
  ? 'insert into public.' + table + ' (' + cols.join(', ') + ') values\n' + rows.map(r => '  (' + r.join(', ') + ')').join(',\n') + (tail ? '\n' + tail : '') + ';\n'
  : '';

const lines = ['-- Generated by backend/seed/build-seed.js from admin-v2/assets/data.js. Do not edit by hand.\n'];

// Currencies and markets
lines.push(insert('currencies', ['code', 'symbol_en', 'symbol_ar', 'decimals', 'per_usd'],
  Object.keys(D.CURRENCIES).map(c => [q(c), q(D.CURRENCIES[c].en), q(D.CURRENCIES[c].ar), n(D.CURRENCIES[c].decimals), n(D.RATES[c])]),
  'on conflict (code) do nothing'));
lines.push(insert('markets', ['id', 'currency', 'price_factor'],
  Object.keys(D.MARKETS).map(m => [q(m), q(D.MARKETS[m].currency), n(D.MARKETS[m].priceFactor)]), 'on conflict (id) do nothing'));

// Categories and subcategories
lines.push(insert('categories', ['id', 'name_en', 'name_ar', 'tint', 'icon', 'intro_en', 'intro_ar', 'pos'],
  D.CATEGORIES.map((c, i) => [q(c.id), q(c.en), q(c.ar), q(c.tint), q(c.icon), q(c.intro && c.intro.en), q(c.intro && c.intro.ar), n(i)]), 'on conflict (id) do nothing'));
lines.push(insert('subcategories', ['category_id', 'id', 'name_en', 'name_ar', 'pos'],
  D.CATEGORIES.flatMap(c => c.subs.map((s, i) => [q(c.id), q(s.id), q(s.en), q(s.ar), n(i)])), 'on conflict (category_id, id) do nothing'));

// Stores (all markets)
const stores = Object.keys(FULL.STORES).flatMap(m => FULL.STORES[m]);
lines.push(insert('stores', ['id', 'market', 'name', 'color', 'categories', 'cpc_usd', 'rating', 'reviews', 'active'],
  stores.map(s => [q(s.id), q(s.market), q(s.name), q(s.color), arr(s.cats), n(s.cpc), n(s.rating), n(s.reviews), s.active === false ? 'false' : 'true']),
  'on conflict (id) do nothing'));

// Products and photos
const products = FULL.PRODUCTS;
lines.push(insert('products', ['id', 'category_id', 'sub_id', 'brand', 'name_en', 'name_ar', 'specs_en', 'specs_ar', 'gtin', 'base_usd', 'drop_pct', 'rating', 'reviews', 'status'],
  products.map(p => [q(p.id), q(p.cat), q(p.sub), q(p.brand), q(p.en), q(p.ar), arr((p.specs || {}).en || []), arr((p.specs || {}).ar || []),
    q(p.gtin), n(p.base), n(p.drop), n(p.rating), n(p.reviews), q(p.status)]), 'on conflict (id) do nothing'));
lines.push(insert('product_photos', ['product_id', 'pos', 'photo_id', 'credit'],
  products.flatMap(p => (p.photos || []).map((ph, i) => [q(p.id), n(i), q(ph.id), q(ph.by)])), 'on conflict (product_id, pos) do nothing'));

// Offers: the demo generates them deterministically per product and market
const offerRows = [];
Object.keys(D.MARKETS).forEach(m => {
  products.forEach(p => {
    D.offersFor(p, m).forEach(o => {
      offerRows.push([q(p.id), q(o.store.id), q(m), q(o.currency), n(o.price), n(o.shipping), n(o.was), o.inStock ? 'true' : 'false',
        n(o.days[0]), n(o.days[1]), n(o.variant), q(o.trackingId), "now() - interval '" + o.updatedMin + " minutes'"]);
    });
  });
});
lines.push(insert('offers', ['product_id', 'store_id', 'market', 'currency', 'price', 'shipping', 'was_price', 'in_stock', 'delivery_min', 'delivery_max', 'variant', 'tracking_id', 'updated_at'],
  offerRows, 'on conflict (product_id, store_id) do nothing'));

// Coupons and popular searches
lines.push(insert('coupons', ['store_name', 'market', 'code', 'title_en', 'title_ar', 'category_id', 'expires_on'],
  D.COUPONS.map(c => [q(c.store), q(c.market), q(c.code), q(c.en), q(c.ar), q(c.cat), 'current_date + ' + n(c.days)])));
lines.push(insert('popular_searches', ['pos', 'term'], D.POPULAR.map((t, i) => [n(i), q(t)]), 'on conflict (pos) do nothing'));

fs.mkdirSync(OUT, { recursive: true });
fs.writeFileSync(path.join(OUT, '01-catalog.sql'), lines.join('\n'));

// Price history: lowest price per product and market per day. Only days where the value changed are kept.
const hist = [];
const catHistory = {};
const isoDay = off => { const d = new Date(); d.setHours(0, 0, 0, 0); d.setDate(d.getDate() - off); return d.getFullYear() + '-' + String(d.getMonth() + 1).padStart(2, '0') + '-' + String(d.getDate()).padStart(2, '0'); };
Object.keys(D.MARKETS).forEach(m => {
  products.forEach(p => {
    const series = D.historyFor(p, m, HISTORY_DAYS);
    let last = null;
    series.forEach((v, i) => {
      const val = Math.round(v * 100) / 100;
      if (val === last) return;
      last = val;
      hist.push([q(p.id), q(m), 'current_date - ' + (series.length - 1 - i), n(val)]);
      (catHistory[p.id + '|' + m] = catHistory[p.id + '|' + m] || []).push([isoDay(series.length - 1 - i), val]);
    });
  });
});

// The same catalog as one JSON document: this is what the database function get_catalog() returns and what
// assets/boot.js hands to data.js. Written for offline tests (backend/tests/parity.js) and for trying the loader without a database.
const catalog = {
  rates: D.RATES, currencies: D.CURRENCIES, markets: D.MARKETS,
  categories: D.CATEGORIES.map(c => ({ id: c.id, en: c.en, ar: c.ar, tint: c.tint, icon: c.icon, intro: c.intro, subs: c.subs.map(s => ({ id: s.id, en: s.en, ar: s.ar })) })),
  stores: Object.keys(FULL.STORES).reduce((o, m) => { o[m] = FULL.STORES[m].map(s => ({ id: s.id, name: s.name, cats: s.cats, color: s.color, cpc: s.cpc, rating: s.rating, reviews: s.reviews, active: s.active !== false, market: m })); return o; }, {}),
  products: products.map(p => ({ id: p.id, cat: p.cat, sub: p.sub, brand: p.brand, en: p.en, ar: p.ar, specs: p.specs, gtin: p.gtin, base: p.base, drop: p.drop, rating: p.rating, reviews: p.reviews, status: p.status, photos: p.photos })),
  offers: {}, history: catHistory,
  coupons: D.COUPONS.map(c => ({ store: c.store, market: c.market, code: c.code, en: c.en, ar: c.ar, cat: c.cat, days: c.days, active: c.active !== false })),
  popular: D.POPULAR
};
Object.keys(D.MARKETS).forEach(m => products.forEach(p => {
  catalog.offers[p.id + '|' + m] = D.offersFor(p, m).map(o => ({ storeId: o.store.id, price: o.price, shipping: o.shipping, currency: o.currency, was: o.was, inStock: o.inStock,
    daysMin: o.days[0], daysMax: o.days[1], updatedMin: o.updatedMin, variant: o.variant, trackingId: o.trackingId, url: null }));
}));
fs.writeFileSync(path.join(ROOT, 'backend', 'seed', 'catalog.local.json'), JSON.stringify(catalog));
fs.writeFileSync(path.join(OUT, '02-history.sql'), '-- Generated by build-seed.js\n' + insert('price_history', ['product_id', 'market', 'day', 'lowest'], hist, 'on conflict do nothing'));

console.log('stores', stores.length, '| products', products.length, '| offers', offerRows.length, '| coupons', D.COUPONS.length, '| history rows', hist.length);
console.log('written to', OUT);
